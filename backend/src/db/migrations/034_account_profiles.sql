CREATE TABLE IF NOT EXISTS account_profiles (
  user_id CHAR(36) PRIMARY KEY,
  phone VARCHAR(30) NOT NULL DEFAULT '',
  organization VARCHAR(160) NOT NULL DEFAULT '',
  job_title VARCHAR(120) NOT NULL DEFAULT '',
  city VARCHAR(120) NOT NULL DEFAULT '',
  state VARCHAR(120) NOT NULL DEFAULT '',
  bio VARCHAR(1000) NOT NULL DEFAULT '',
  avatar_mime VARCHAR(100) NULL,
  avatar_data MEDIUMBLOB NULL,
  avatar_version INT NOT NULL DEFAULT 0,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT fk_account_profiles_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);
