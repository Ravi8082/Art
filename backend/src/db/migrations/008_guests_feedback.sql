CREATE TABLE IF NOT EXISTS guests (
  id CHAR(36) PRIMARY KEY,
  name VARCHAR(120) NOT NULL,
  role VARCHAR(160) NOT NULL DEFAULT '',
  event_name VARCHAR(160) NOT NULL DEFAULT '',
  bio VARCHAR(1200) NOT NULL DEFAULT '',
  photo_asset_id CHAR(36) NULL,
  instagram_url VARCHAR(500) NULL,
  website_url VARCHAR(500) NULL,
  sort_order SMALLINT UNSIGNED NOT NULL DEFAULT 0,
  active TINYINT(1) NOT NULL DEFAULT 1,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  FOREIGN KEY(photo_asset_id) REFERENCES media_assets(id) ON DELETE SET NULL,
  INDEX idx_guests_order(sort_order)
);

CREATE TABLE IF NOT EXISTS guest_feedback (
  id CHAR(36) PRIMARY KEY,
  guest_id CHAR(36) NULL,
  author_name VARCHAR(120) NOT NULL,
  author_role VARCHAR(160) NOT NULL DEFAULT '',
  message VARCHAR(900) NOT NULL,
  rating TINYINT UNSIGNED NOT NULL DEFAULT 5,
  sort_order SMALLINT UNSIGNED NOT NULL DEFAULT 0,
  active TINYINT(1) NOT NULL DEFAULT 1,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  FOREIGN KEY(guest_id) REFERENCES guests(id) ON DELETE SET NULL,
  INDEX idx_guest_feedback_order(sort_order)
);
